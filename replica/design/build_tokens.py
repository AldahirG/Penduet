#!/usr/bin/env python3
"""tokens.json + tokens.dark.json -> tokens.css + tailwind.config.ts. Standard library only.

    python3 build_tokens.py

Edit the JSON, never the generated files. After a palette change run, in order:
    python3 contrast.py tokens.json && python3 contrast.py tokens.dark.json && python3 build_tokens.py
"""

import json
import pathlib

HERE = pathlib.Path(__file__).parent

# Token name -> Tailwind colour key. Lets components write bg-surface, text-fg, text-muted,
# border-line, border-input instead of text-text-muted or border-border-input.
TW_COLOR = {
    "bg": "bg",
    "surface": "surface",
    "surface-raised": "raised",
    "border": "line",
    "border-input": "input",
    "text": "fg",
    "text-muted": "muted",
    "accent": "accent",
    "on-accent": "on-accent",
    "accent-soft": "accent-soft",
    "accent-text": "accent-text",
    "danger": "danger",
    "on-danger": "on-danger",
    "success": "success",
    "warning-soft": "warning-soft",
    "warning-text": "warning-text",
    "canvas": "canvas",
    "ink": "ink",
    "guide": "guide",
    "player-1": "player-1",
    "player-2": "player-2",
    "scrim": "scrim",
}


def load(name):
    return json.loads((HERE / name).read_text(encoding="utf-8"))


def px(n):
    return "%spx" % n


def css(light, dark):
    out = ["/* GENERATED by build_tokens.py from tokens.json and tokens.dark.json. Do not edit. */", ""]
    root = []
    for k, v in light["color"].items():
        root.append("  --color-%s: %s;" % (k, v))
    for k, v in light["font"].items():
        root.append("  --font-%s: %s;" % (k, v))
    for k, t in light["type"].items():
        root.append("  --text-%s: %s;" % (k, px(t["size"])))
        root.append("  --text-%s-lh: %s;" % (k, px(t["line"])))
        root.append("  --text-%s-fw: %s;" % (k, t["weight"]))
    for v in light["space"]:
        root.append("  --space-%s: %s;" % (v // 4, px(v)))
    for k, v in light["radius"].items():
        root.append("  --radius-%s: %s;" % (k, px(v)))
    for k, v in light["shadow"].items():
        root.append("  --shadow-%s: %s;" % (k, v))
    for k, v in light["motion"].items():
        root.append("  --motion-%s: %s;" % (k, v))
    lay = light["layout"]
    for k, v in lay.items():
        if k != "breakpoints":
            root.append("  --layout-%s: %s;" % (k, px(v)))
    out += [":root {", "  color-scheme: light;"] + root + ["}", ""]

    changed = [(k, v) for k, v in dark["color"].items() if light["color"].get(k) != v]
    body = ["  color-scheme: dark;"] + ["  --color-%s: %s;" % (k, v) for k, v in changed]
    out += [
        "/* Dark follows the system unless the page sets data-theme explicitly. */",
        "@media (prefers-color-scheme: dark) {",
        "  :root:not([data-theme=\"light\"]) {",
    ] + ["  " + line for line in body] + ["  }", "}", "", ":root[data-theme=\"dark\"] {"] + body + ["}", ""]
    out += [
        "@media (prefers-reduced-motion: reduce) {",
        "  :root { --motion-fast: 0ms; --motion-base: 0ms; }",
        "}",
        "",
    ]
    return "\n".join(out)


def tailwind(light):
    colors = ",\n".join("        '%s': 'var(--color-%s)'" % (TW_COLOR[k], k) for k in light["color"])
    sizes = ",\n".join(
        "        '%s': ['var(--text-%s)', { lineHeight: 'var(--text-%s-lh)', fontWeight: 'var(--text-%s-fw)' }]" % (k, k, k, k)
        for k in light["type"]
    )
    spacing = ",\n".join("        '%s': 'var(--space-%s)'" % (v // 4, v // 4) for v in light["space"])
    radius = ",\n".join("        '%s': 'var(--radius-%s)'" % (k, k) for k in light["radius"])
    shadow = ",\n".join("        '%s': 'var(--shadow-%s)'" % (k, k) for k in light["shadow"])
    screens = ",\n".join("        '%s': '%spx'" % (k, v) for k, v in light["layout"]["breakpoints"].items())
    return """// GENERATED by build_tokens.py from tokens.json. Do not edit.
// Components use roles (bg-surface text-fg text-muted border-line), never raw hex.
// Dark mode is automatic: the CSS variables change, so no dark: variants are needed.
// Tailwind v3 config. For v4 load it with: @config "./tailwind.config.ts";
import type { Config } from 'tailwindcss'

export default {
  content: ['./index.html', './src/**/*.{ts,tsx}'],
  theme: {
    extend: {
      colors: {
%s
      },
      fontFamily: {
        sans: ['var(--font-sans)'],
        display: ['var(--font-display)'],
        mono: ['var(--font-mono)'],
      },
      fontSize: {
%s
      },
      spacing: {
%s
      },
      borderRadius: {
%s
      },
      boxShadow: {
%s
      },
      screens: {
%s
      },
      maxWidth: { content: 'var(--layout-content-max)', canvas: 'var(--layout-canvas-max)' },
      height: { header: 'var(--layout-header-h)', tabbar: 'var(--layout-tabbar-h)', touch: 'var(--layout-touch-min)' },
      width: { touch: 'var(--layout-touch-min)' },
      minHeight: { touch: 'var(--layout-touch-min)' },
      minWidth: { touch: 'var(--layout-touch-min)' },
      transitionDuration: { fast: 'var(--motion-fast)', base: 'var(--motion-base)' },
      transitionTimingFunction: { out: 'var(--motion-ease)' },
    },
  },
} satisfies Config
""" % (colors, sizes, spacing, radius, shadow, screens)


def main():
    light, dark = load("tokens.json"), load("tokens.dark.json")
    missing = set(light["color"]) - set(dark["color"])
    missing |= set(light["color"]) - set(TW_COLOR)
    if missing:
        raise SystemExit("tokens missing in dark theme or Tailwind map: %s" % sorted(missing))
    (HERE / "tokens.css").write_text(css(light, dark), encoding="utf-8")
    (HERE / "tailwind.config.ts").write_text(tailwind(light), encoding="utf-8")
    print("wrote tokens.css and tailwind.config.ts")


if __name__ == "__main__":
    main()
